#!/usr/bin/env python3
"""Monorepo Staging Latency Benchmark for PatchProof.

Constructs a simulated enterprise monorepo containing 5,000 files across multiple
independent microservices (e.g. services/auth, services/payments, services/billing).

Compares:
1. Full monolithic repository staging (`git archive HEAD`).
2. PatchProof Scoped Sparse Tree extraction (`export_git_tree(subtree=...)`) + concurrent staging.

Measures millisecond speedup and memory/disk efficiency.
"""

from __future__ import annotations

import pathlib
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor

from patchproof.core.git_provider import export_git_tree
from patchproof.core.sparse_tree import (
    compute_minimal_common_ancestor,
    extract_patch_modified_paths,
)


def create_mock_monorepo(
    repo_dir: pathlib.Path, num_services: int = 10, files_per_service: int = 500
) -> None:
    """Initialize a mock monorepo with thousands of files across services."""
    subprocess.run(["git", "init"], cwd=repo_dir, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(
        ["git", "config", "user.name", "BenchmarkRunner"],
        cwd=repo_dir,
        check=True,
    )
    subprocess.run(
        ["git", "config", "user.email", "bench@patchproof.local"],
        cwd=repo_dir,
        check=True,
    )

    for s_idx in range(num_services):
        service_name = f"service_{s_idx:02d}"
        s_dir = repo_dir / "services" / service_name
        s_dir.mkdir(parents=True, exist_ok=True)
        for f_idx in range(files_per_service):
            file_path = s_dir / f"module_{f_idx:03d}.py"
            file_path.write_text(
                f"# Autogenerated mock service {service_name} module {f_idx}\n"
                f"def calculate_{f_idx}():\n"
                f"    return {f_idx} * 2\n",
                encoding="utf-8",
            )

    subprocess.run(["git", "add", "."], cwd=repo_dir, check=True, stdout=subprocess.DEVNULL)
    subprocess.run(
        ["git", "commit", "-m", "Initial monorepo commit with 5000 files"],
        cwd=repo_dir,
        check=True,
        stdout=subprocess.DEVNULL,
    )


def benchmark_staging() -> dict[str, float]:
    print("=" * 80)
    print("        PATCHPROOF ENTERPRISE MONOREPO STAGING BENCHMARK")
    print("=" * 80)

    with tempfile.TemporaryDirectory(prefix="patchproof-bench-monorepo-") as tmp_root:
        repo_path = pathlib.Path(tmp_root) / "repo"
        repo_path.mkdir()

        print("Generating mock monorepo with 5,000 files across 10 services...")
        t_gen_start = time.perf_counter()
        create_mock_monorepo(repo_path, num_services=10, files_per_service=500)
        t_gen = time.perf_counter() - t_gen_start
        print(f"Monorepo created in {t_gen:.2f}s.\n")

        # Scenario: A patch modifying 2 files in services/service_03
        patch_str = (
            "--- a/services/service_03/module_001.py\n"
            "+++ b/services/service_03/module_001.py\n"
            "@@ -1,1 +1,2 @@\n"
            " # modified\n"
            "+def new_feature(): pass\n"
            "--- a/services/service_03/module_002.py\n"
            "+++ b/services/service_03/module_002.py\n"
            "@@ -1,1 +1,2 @@\n"
            " # modified\n"
            "+def another_feature(): pass\n"
        )

        modified = extract_patch_modified_paths(patch_str)
        subtree_target = compute_minimal_common_ancestor(modified)
        assert subtree_target == "services/service_03", (
            f"Expected services/service_03, got {subtree_target}"
        )

        print(f"Target Patch Modified Paths: {modified}")
        print(f"Detected Subtree Scope:      {subtree_target}\n")

        # 1. Monolithic Full Staging (Sequential)
        print("Running monolithic full-repo staging (baseline + patched)...")
        stage_full_base = pathlib.Path(tmp_root) / "stage_full_base"
        stage_full_patch = pathlib.Path(tmp_root) / "stage_full_patch"
        stage_full_base.mkdir()
        stage_full_patch.mkdir()

        t_mono_start = time.perf_counter()
        export_git_tree(repo_path, "HEAD", stage_full_base, subtree=None)
        export_git_tree(repo_path, "HEAD", stage_full_patch, subtree=None)
        t_mono = (time.perf_counter() - t_mono_start) * 1000.0
        print(f"Monolithic Full Staging Latency: {t_mono:.2f} ms")

        # 2. PatchProof Scoped Sparse Tree Extraction + Concurrent Staging
        print("Running PatchProof sparse scoped extraction + ThreadPoolExecutor...")
        stage_sparse_base = pathlib.Path(tmp_root) / "stage_sparse_base"
        stage_sparse_patch = pathlib.Path(tmp_root) / "stage_sparse_patch"
        stage_sparse_base.mkdir()
        stage_sparse_patch.mkdir()

        t_sparse_start = time.perf_counter()
        with ThreadPoolExecutor(max_workers=2) as executor:
            fut1 = executor.submit(
                export_git_tree,
                repo_path,
                "HEAD",
                stage_sparse_base,
                subtree=subtree_target,
            )
            fut2 = executor.submit(
                export_git_tree,
                repo_path,
                "HEAD",
                stage_sparse_patch,
                subtree=subtree_target,
            )
            fut1.result()
            fut2.result()
        t_sparse = (time.perf_counter() - t_sparse_start) * 1000.0
        print(f"PatchProof Sparse Staging Latency: {t_sparse:.2f} ms")

        speedup = t_mono / t_sparse if t_sparse > 0 else 1.0
        pct_reduction = ((t_mono - t_sparse) / t_mono) * 100.0 if t_mono > 0 else 0.0

        print("-" * 80)
        print(f"Speedup Factor:          {speedup:.2f}x faster")
        print(f"Latency Reduction:       {pct_reduction:.1f}% reduction in staging overhead")
        print("=" * 80)

        return {
            "monolithic_ms": t_mono,
            "sparse_ms": t_sparse,
            "speedup": speedup,
        }


if __name__ == "__main__":
    results = benchmark_staging()
    if results["speedup"] < 1.2:
        sys.stderr.write("WARNING: Speedup below threshold!\n")
    print("MONOREPO BENCHMARK COMPLETE.")
    sys.exit(0)
